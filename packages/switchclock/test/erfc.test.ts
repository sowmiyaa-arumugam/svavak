import { describe, expect, it } from 'vitest'; // test API
import { erfc } from '../src/core/erfc.ts'; // under test: the port of FreeBSD's s_erf.c erfc
import pkg from '../package.json'; // the package manifest, for its dependencies
import reference from './erfc-reference.json'; // generated by erfc-reference.py: exact erfc at exact double inputs

const MIN_NORMAL = 2.2250738585072014e-308; // smallest normal double
const MAX_ULPS = 4; // "a few ulps": at most 4 units in the last place
const BRANCHES = ['nan-inf', 'tiny', 'small', 'quarter', 'near-one+', 'near-one-', 'mid+', 'mid-', 'tail+', 'tail-', 'minus-six', 'huge+', 'huge-']; // every branch of s_erf.c's erfc
const view = new DataView(new ArrayBuffer(8)); // scratch space for a double's bits
const bits = (x: number): bigint => { // a double's 64 bits as a signed integer
  view.setFloat64(0, x); // write the double
  return view.getBigInt64(0); // read its bits back
}; // end of bits
const ulps = (a: number, b: number): number => { // distance in units in the last place, for two non-negative doubles
  const d = bits(a) - bits(b); // non-negative doubles order like their bit patterns
  return Number(d < 0n ? -d : d); // the absolute distance
}; // end of ulps
const cases = reference.cases.map(([x, y, branch]) => ({ x: Number(x), y: Number(y), branch: branch! })); // the strings as doubles

describe('erfc', () => { // the port of FreeBSD's s_erf.c erfc
  it('is tested on every branch of the algorithm', () => { // the fixture's coverage
    const counts = new Map<string, number>(); // inputs per branch
    for (const c of cases) counts.set(c.branch, (counts.get(c.branch) ?? 0) + 1); // count them
    expect([...counts.keys()].sort()).toEqual([...BRANCHES].sort()); // all 13 branches, and nothing else
    for (const b of BRANCHES) expect(counts.get(b)).toBeGreaterThanOrEqual(b === 'nan-inf' ? 3 : 300); // dense in each
  }); // end of the case
  it('handles NaN, both zeros and both infinities', () => { // the special values
    expect(erfc(NaN)).toBeNaN(); // erfc(NaN) = NaN
    expect(erfc(0)).toBe(1); // erfc(+0) = 1
    expect(erfc(-0)).toBe(1); // erfc(-0) = 1
    expect(erfc(Infinity)).toBe(0); // erfc(+inf) = 0
    expect(erfc(-Infinity)).toBe(2); // erfc(-inf) = 2
  }); // end of the case
  it(`is within ${MAX_ULPS} ulps (and 1e-15 relative) of the exact value wherever the result is a normal number`, () => { // accuracy
    let worstUlps = 0; // the largest distance seen
    let worstRelative = 0; // the largest relative error seen
    for (const { x, y } of cases) { // each input
      if (Number.isNaN(y) || y < MIN_NORMAL) continue; // NaN, zero and subnormal results are checked below
      const got = erfc(x); // the port's value
      worstUlps = Math.max(worstUlps, ulps(got, y)); // in ulps
      worstRelative = Math.max(worstRelative, Math.abs(got - y) / y); // relative
    } // end of the inputs
    expect(worstUlps).toBeLessThanOrEqual(MAX_ULPS); // a few ulps
    expect(worstRelative).toBeLessThanOrEqual(1e-15); // about 1e-15
  }); // end of the case
  it(`is within ${MAX_ULPS} subnormal ulps where the exact value is subnormal or underflows to 0`, () => { // the far right tail
    let checked = 0; // inputs in this range
    for (const { x, y } of cases) { // each input
      if (Number.isNaN(y) || y >= MIN_NORMAL) continue; // only results below the normal range
      expect(ulps(erfc(x), y)).toBeLessThanOrEqual(MAX_ULPS); // counted on the subnormal grid (2**-1074)
      checked++; // one more
    } // end of the inputs
    expect(checked).toBeGreaterThan(100); // the tail is really covered
  }); // end of the case
}); // end of erfc

describe('switchclock package', () => { // what it ships
  it('has no runtime dependencies', () => { // erfc is ported, not imported
    expect(pkg).not.toHaveProperty('dependencies'); // nothing installed for consumers
  }); // end of the case
}); // end of switchclock package
